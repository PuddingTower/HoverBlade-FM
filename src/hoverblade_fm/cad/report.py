"""Manufacturing report and package manifest (T080, T081)."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

from hoverblade_fm import __version__
from hoverblade_fm.cad import backend
from hoverblade_fm.cad.checks import TOLERANCES, ManufacturingChecks
from hoverblade_fm.cad.dxf import DETAIL_X_OVER_C
from hoverblade_fm.config.schema import ResolvedConfig
from hoverblade_fm.models import Design

ROLE_BY_NAME = {
    "blade.step": "3D solid for CAD, mould design and CNC reference",
    "blade.stl": "watertight triangulation for 3D printing and toolpaths",
    "master_sections.dxf": "2D master templates for lofting, trimming and inspection",
    "manufacturing_report.md": "check results, tolerances and reading instructions",
    "manifest.json": "package contents with sizes and SHA-256 digests",
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _fmt(value: float, digits: int = 4) -> str:
    return "n/a" if value is None or not np.isfinite(value) else f"{value:.{digits}f}"


def write_manufacturing_report(
    design: Design,
    cfg: ResolvedConfig,
    checks: ManufacturingChecks,
    out_dir: Path,
    *,
    performance: dict[str, Any] | None = None,
) -> Path:
    """Write ``cad/manufacturing_report.md`` covering plan section 13.3."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    now = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    status = "PASS" if checks.ok else "FAIL"

    lines: list[str] = []
    lines.append("# Manufacturing report")
    lines.append("")
    lines.append(f"Generated by HoverBlade-FM {__version__} on {now}. Units: **millimetres** throughout.")
    lines.append("")
    lines.append(f"**Package status: {status}**")
    lines.append("")
    if checks.blocking_failures:
        lines.append("## Blocking failures")
        lines.append("")
        for item in checks.blocking_failures:
            lines.append(f"- {item}")
        lines.append("")
    if checks.warnings:
        lines.append("## Warnings")
        lines.append("")
        for item in checks.warnings:
            lines.append(f"- {item}")
        lines.append("")

    lines.append("## Design summary")
    lines.append("")
    lines.append("| item | value |")
    lines.append("|---|---|")
    lines.append(f"| rotor radius | {_fmt(cfg.radius_m * 1000, 1)} mm |")
    lines.append(f"| blade count | {design.blade_count} |")
    lines.append(f"| design thrust | {_fmt(cfg.thrust_n, 1)} N |")
    lines.append(f"| rotor speed | {_fmt(design.rpm, 1)} RPM |")
    lines.append(f"| tip speed | {_fmt(design.tip_speed, 1)} m/s |")
    lines.append(f"| solidity | {_fmt(design.solidity, 4)} |")
    lines.append(f"| hub radius | {_fmt(cfg.radius_m * cfg.solver.root_extension_r * 1000, 1)} mm |")
    lines.append(f"| CAD backend | {backend.name()} |")
    if performance:
        lines.append(f"| figure of merit | {_fmt(float(performance.get('figure_of_merit', 0.0)), 4)} |")
        lines.append(
            f"| hover power | {_fmt(float(performance.get('power_actual_w', 0.0)) / 1000.0, 2)} kW |"
        )
    lines.append("")

    lines.append("## Blunt trailing edge (hard constraint)")
    lines.append("")
    lines.append(
        f"The trailing-edge gap is an explicit degree of freedom of the CST parameterisation and is "
        f"projected onto the user minimum at decode time, so a sharp trailing edge cannot be produced. "
        f"Required minimum: **{_fmt(cfg.te_min_m * 1000, 3)} mm**; smallest value in this design: "
        f"**{_fmt(checks.min_te_thickness_global_m * 1000, 3)} mm** (margin {_fmt(checks.te_thickness_margin_m * 1000, 3)} mm)."
    )
    lines.append("")
    lines.append(
        "| station | r/R | chord mm | twist deg | t_TE mm | t_TE/c | margin mm | wedge deg | TE radius mm | ok |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for i, section in enumerate(design.sections):
        te = checks.min_te_thickness_per_section_m[i]
        angle = checks.te_included_angle_deg_per_section[i]
        radius = checks.te_radius_per_section_m[i]
        ok = te >= cfg.te_min_m - 1e-12 and 0 < te / section.chord_m <= cfg.airfoil.te_over_chord_max + 1e-9
        lines.append(
            f"| {section.station_id} | {_fmt(section.r_R, 3)} | {_fmt(section.chord_m * 1000, 2)} | "
            f"{_fmt(section.twist_deg, 2)} | {_fmt(te * 1000, 3)} | {_fmt(te / section.chord_m, 5)} | "
            f"{_fmt((te - cfg.te_min_m) * 1000, 3)} | {_fmt(angle, 2)} | {_fmt(radius * 1000, 3)} | "
            f"{'PASS' if ok else 'FAIL'} |"
        )
    lines.append("")

    lines.append("## Check matrix (plan section 13.3)")
    lines.append("")
    lines.append("| check | requirement | result | status |")
    lines.append("|---|---|---|---|")
    rows = [
        (
            "minimum trailing-edge thickness",
            f">= {_fmt(cfg.te_min_m * 1000, 3)} mm",
            f"{_fmt(checks.min_te_thickness_global_m * 1000, 3)} mm",
            checks.min_te_thickness_global_m >= cfg.te_min_m,
        ),
        (
            "trailing edge continuity",
            "no degenerate sharp edge",
            "explicit gap on every station",
            checks.te_manufacturability_flag,
        ),
        (
            "chord change rate",
            f"<= {checks.chord_change_rate_limit:.2f} (d(c/R)/d(r/R))",
            f"{checks.chord_change_rate_max:.3f}",
            checks.chord_change_rate_max <= checks.chord_change_rate_limit + 1e-6,
        ),
        (
            "twist change rate",
            f"<= {checks.twist_change_rate_limit:.1f} deg per r/R",
            f"{checks.twist_change_rate_deg_per_r_max:.2f}",
            checks.twist_change_rate_deg_per_r_max <= checks.twist_change_rate_limit + 1e-6,
        ),
        (
            "surface quality",
            "no self-intersection",
            "detected" if checks.surface_self_intersection_detected else "none",
            not checks.surface_self_intersection_detected,
        ),
        (
            "loft error",
            f"<= {checks.loft_error_limit_m * 1000:.3f} mm",
            f"{checks.loft_max_gap_error_m * 1000:.4f} mm",
            checks.loft_max_gap_error_m <= checks.loft_error_limit_m,
        ),
        (
            "STL watertightness",
            "closed manifold",
            "watertight" if checks.mesh_watertight else "open",
            checks.mesh_watertight,
        ),
        ("mesh volume", "> 0", f"{checks.mesh_volume_m3:.6f} m^3", checks.mesh_volume_m3 > 0),
        (
            "STEP readability",
            "structurally valid AP214",
            f"{checks.step_entities} entities" if checks.step_parse_ok else "unreadable",
            checks.step_parse_ok,
        ),
        (
            "DXF templates",
            "10 section polylines + TE details",
            f"{checks.dxf_section_polylines} section polylines",
            checks.dxf_written,
        ),
        ("units", "declared explicitly", checks.units, True),
    ]
    for name, requirement, result, passed in rows:
        lines.append(f"| {name} | {requirement} | {result} | {'PASS' if passed else 'FAIL'} |")
    lines.append("")

    lines.append("## Tolerances (defaults, configurable)")
    lines.append("")
    for name, value in TOLERANCES.items():
        lines.append(f"- **{name.replace('_', ' ')}**: {value}")
    lines.append("")

    lines.append("## How to use these files")
    lines.append("")
    lines.append(
        "- `blade.step` - open in FreeCAD / Fusion / any OCCT reader; it is a single solid manifold."
    )
    lines.append(
        "- `blade.stl` - watertight triangulation; slices and 5-axis toolpaths can be derived directly."
    )
    lines.append(
        f"- `master_sections.dxf` - one closed template polyline per station plus a magnified "
        f"trailing-edge detail (region x/c > {DETAIL_X_OVER_C:g}) on layer `TE_MARKERS`; the `DATUM_25C` line is the "
        "25% chord rotation reference used by the coordinate files."
    )
    lines.append(
        "- Section coordinates are also available as CSV in `../sections/` with normalised and physical columns."
    )
    lines.append("")
    lines.append("## Statement on the trailing-edge constraint")
    lines.append("")
    lines.append(
        "A sharp trailing edge is impossible in this package by construction: the geometry generator projects "
        "every station onto the specified minimum thickness before any file is written, and this report re-measures "
        "the produced coordinates rather than trusting the request."
    )
    lines.append("")
    lines.append("## Disclaimer")
    lines.append("")
    lines.append(
        "Aerodynamic shape and manufacturing geometry only; not a structural, fatigue, dynamics or airworthiness approval."
    )
    lines.append("")
    report_path = out_dir / "manufacturing_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path


def write_manifest(out_dir: Path, *, checks: ManufacturingChecks) -> Path:
    """Write ``cad/manifest.json`` (T081): what a manufacturer is being handed."""
    out_dir = Path(out_dir)
    entries: list[dict[str, Any]] = []
    for path in sorted(out_dir.iterdir()):
        if not path.is_file() or path.name == "manifest.json":
            continue
        entries.append(
            {
                "file": path.name,
                "role": ROLE_BY_NAME.get(path.name, "supporting output"),
                "bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
        )
    payload = {
        "package": "HoverBlade-FM manufacturing package",
        "units": "MM",
        "generated_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "files": entries,
        "package_ok": bool(checks.ok),
        "blocking_failures": checks.blocking_failures,
    }
    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    return manifest_path


__all__ = ["ROLE_BY_NAME", "write_manifest", "write_manufacturing_report"]
